CREATE TABLE QUOCGIA (
	MAQG	VARCHAR(5)	PRIMARY KEY,
	TENQG	VARCHAR(60)	NOT NULL UNIQUE
);

CREATE TABLE TINH (
	MATINH	VARCHAR(5)	PRIMARY KEY,
	TENTINH	VARCHAR(100)	NOT NULL UNIQUE
);

CREATE TABLE SANVD (
	MASAN	VARCHAR(5)	PRIMARY KEY,
	TENSAN	VARCHAR(100)	NOT NULL UNIQUE,
	DIACHI	VARCHAR(200)
);

CREATE TABLE CAULACBO (
	MACLB	VARCHAR(5)	PRIMARY KEY,
	TENCLB	VARCHAR(100)	NOT NULL,
	MASAN	VARCHAR(5)	NOT NULL REFERENCES SANVD(MASAN),
	MATINH	VARCHAR(5)	NOT NULL REFERENCES TINH(MATINH)
);

CREATE TABLE CAUTHU (
	MACT	INT	GENERATED BY DEFAULT AS IDENTITY	PRIMARY KEY,
	HOTEN	VARCHAR(100)	NOT NULL,
	VITRI	VARCHAR(20)		NOT NULL	CHECK (VITRI IN('Thủ môn','Tiền đạo','Tiền vệ','Trung vệ','Hậu vệ')),
	NGAYSINH	TIMESTAMP,
	DIACHI	VARCHAR(200),
	MACLB	VARCHAR(5)	NOT NULL REFERENCES CAULACBO(MACLB),
	MAQG	VARCHAR(5)	NOT NULL REFERENCES QUOCGIA(MAQG),
	SO		INT			NOT NULL,
	UNIQUE (MACLB, SO)
);

CREATE TABLE HUANLUYENVIEN (
	MAHLV	VARCHAR(5)	PRIMARY KEY,
	TENHLV	VARCHAR(100)	NOT NULL,
	NGAYSINH	TIMESTAMP,
	DIACHI		VARCHAR(200),
	DIENTHOAI	VARCHAR(20),
	MAQG	VARCHAR(5)	NOT NULL REFERENCES QUOCGIA(MAQG)
);

CREATE TABLE HLV_CLB (
	MAHLV	VARCHAR(5)	REFERENCES HUANLUYENVIEN(MAHLV),
	MACLB	VARCHAR(5)	REFERENCES CAULACBO(MACLB),
	VAITRO	VARCHAR(100)	NOT NULL	CHECK (LOWER(VAITRO) IN ('hlv chính','hlv phụ','hlv thủ môn','hlv thể lực')),
	PRIMARY KEY (MAHLV, MACLB)
);

CREATE TABLE TRANDAU (
	MATRAN INT GENERATED BY DEFAULT AS IDENTITY	PRIMARY KEY,
	NAM		INT		NOT NULL,
	VONG	INT		NOT NULL,
	NGAYTD	TIMESTAMP	NOT NULL,
	MACLB1	VARCHAR(5)	NOT NULL	REFERENCES CAULACBO(MACLB),
	MACLB2	VARCHAR(5)	NOT NULL	REFERENCES CAULACBO(MACLB),
	MASAN	VARCHAR(5)	NOT NULL	REFERENCES SANVD(MASAN),
	KETQUA	VARCHAR(5)	NOT NULL
);

CREATE TABLE BANGXH (
	MACLB	VARCHAR(5)	REFERENCES CAULACBO(MACLB),
	NAM		INT,
	VONG	INT,
	SOTRAN	INT		NOT NULL,
	THANG	INT		NOT NULL,
	HOA		INT		NOT NULL,
	THUA	INT		NOT NULL,
	HIEUSO	VARCHAR(5)	NOT NULL,
	DIEM	INT		NOT NULL,
	HANG	INT		NOT NULL,
	PRIMARY KEY (MACLB, NAM, VONG)
);

